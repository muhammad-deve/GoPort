package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

func runReport(args []string) error {
	var files []string
	for _, a := range args {
		matches, err := filepath.Glob(a)
		if err != nil || len(matches) == 0 {
			files = append(files, a)
			continue
		}
		files = append(files, matches...)
	}
	if len(files) == 0 {
		return errors.New("usage: tunnelbench report results/DATE/*.json")
	}

	var runs []*Result
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		var r Result
		if err := json.Unmarshal(data, &r); err != nil {
			return fmt.Errorf("%s: %w", f, err)
		}
		runs = append(runs, &r)
	}
	sort.SliceStable(runs, func(i, j int) bool { return runs[i].StartedAt.Before(runs[j].StartedAt) })

	writeReport(os.Stdout, runs)
	return nil
}

type targetGroup struct {
	name string
	runs []*Result
}

func groupByTarget(runs []*Result) []targetGroup {
	index := map[string]int{}
	var groups []targetGroup
	for _, r := range runs {
		i, ok := index[r.Target]
		if !ok {
			i = len(groups)
			index[r.Target] = i
			groups = append(groups, targetGroup{name: r.Target})
		}
		groups[i].runs = append(groups[i].runs, r)
	}
	sort.SliceStable(groups, func(i, j int) bool { return groups[i].name < groups[j].name })
	return groups
}

func writeReport(w io.Writer, runs []*Result) {
	p := func(format string, a ...any) { fmt.Fprintf(w, format, a...) }

	first, last := runs[0], runs[len(runs)-1]
	p("# Tunnel benchmark summary\n\n")
	p("Generated by `tunnelbench report` from %d result files. Every run is listed; nothing was filtered out.\n\n", len(runs))

	p("## Environment\n\n")
	p("- Runs: %s to %s (UTC)\n", first.StartedAt.Format(time.RFC3339), last.FinishedAt.Format(time.RFC3339))
	for _, v := range distinct(runs, func(r *Result) string {
		return fmt.Sprintf("%s/%s, %s, %d logical CPUs, %s", r.Env.OS, r.Env.Arch, r.Env.CPU, r.Env.NumCPU, r.Env.GoVersion)
	}) {
		p("- Machine: %s\n", v)
	}
	for _, v := range distinct(runs, func(r *Result) string { return r.Env.OSVersion }) {
		if v != "" {
			p("- OS version: %s\n", v)
		}
	}
	s := first.Settings
	p("- Per run: %d sequential `GET /ping` (after %d warm-up), up to %d `GET /ping` over %d workers (phase capped at %.0f s), %d × %s download, %d × %s upload, %d WebSocket echoes of %d bytes\n\n",
		s.LatencyRequests, s.Warmup, s.ConcurrencyRequests, s.ConcurrencyWorkers, s.ConcurrencyMaxSec,
		s.Downloads, humanBytes(s.DownloadBytes), s.Uploads, humanBytes(s.UploadBytes), s.WSMessages, s.WSMessageBytes)

	groups := groupByTarget(runs)

	p("## Median of rounds per target\n\n")
	p("Each cell is the median across runs of that run's figure. Throughput is the median of every completed transfer; when no transfer completed, the rate reached before the timeout is shown as `~x (timed out)`. Error columns are totals across all runs; the concurrency total counts requests actually sent before that phase's time cap. `—` means the phase produced no successful sample.\n\n")
	p("| Target | Runs | TCP connect to edge (ms) | Latency median (ms) | Latency p95 (ms) | Latency p99 (ms) | Latency errors | Concurrent req/s | Concurrent p95 (ms) | Concurrent errors | Download MB/s | Upload MB/s | Failed transfers | WS RTT median (ms) | WS failures | WS stayed up |\n")
	p("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
	for _, g := range groups {
		var probe, latMed, latP95, latP99, concRPS, concP95, dl, ul, dlPartial, ulPartial, wsMed []float64
		var latErr, latReq, concErr, concReq, failedXfer, totalXfer, wsFail, wsMsgs, stayed int
		for _, r := range g.runs {
			if len(r.Probes) > 0 && r.Probes[0].OK > 0 {
				probe = append(probe, r.Probes[0].MedianMs)
			}
			if st := r.Latency.Stats; st != nil {
				latMed = append(latMed, st.Median)
				latP95 = append(latP95, st.P95)
				latP99 = append(latP99, st.P99)
			}
			latErr += r.Latency.Errors
			latReq += r.Latency.Requests
			if st := r.Concurrency.Stats; st != nil {
				concRPS = append(concRPS, r.Concurrency.ReqPerSec)
				concP95 = append(concP95, st.P95)
			}
			concErr += r.Concurrency.Errors
			concReq += r.Concurrency.Sent
			for _, t := range r.Downloads {
				totalXfer++
				if t.OK {
					dl = append(dl, t.MBps)
				} else {
					failedXfer++
					if t.PartialMBps > 0 {
						dlPartial = append(dlPartial, t.PartialMBps)
					}
				}
			}
			for _, t := range r.Uploads {
				totalXfer++
				if t.OK {
					ul = append(ul, t.MBps)
				} else {
					failedXfer++
					if t.PartialMBps > 0 {
						ulPartial = append(ulPartial, t.PartialMBps)
					}
				}
			}
			if st := r.WebSocket.Stats; st != nil {
				wsMed = append(wsMed, st.Median)
			}
			wsFail += r.WebSocket.Failures
			wsMsgs += r.WebSocket.Messages
			if r.WebSocket.StayedUp {
				stayed++
			}
		}
		p("| %s | %d | %s | %s | %s | %s | %d / %d | %s | %s | %d / %d | %s | %s | %d / %d | %s | %d / %d | %d / %d |\n",
			g.name, len(g.runs), med(probe, 1), med(latMed, 1), med(latP95, 1), med(latP99, 1), latErr, latReq,
			med(concRPS, 1), med(concP95, 1), concErr, concReq, rate(dl, dlPartial), rate(ul, ulPartial), failedXfer, totalXfer,
			med(wsMed, 1), wsFail, wsMsgs, stayed, len(g.runs))
	}

	p("\n## Client versions, regions and notes\n\n")
	p("| Target | Client version | Region / edge | Protocol seen | Notes |\n|---|---|---|---|---|\n")
	for _, g := range groups {
		p("| %s | %s | %s | %s | %s |\n", g.name,
			cell(distinct(g.runs, func(r *Result) string { return r.ClientVersion })),
			cell(distinct(g.runs, func(r *Result) string { return r.Region })),
			cell(distinct(g.runs, func(r *Result) string { return r.Latency.Protocol })),
			cell(distinct(g.runs, func(r *Result) string { return r.Notes })))
	}

	p("\n## Every run\n\n")
	p("| Target | Round | Started (UTC) | TCP connect (ms) | Latency median / p95 / p99 (ms) | Latency errors | Concurrent req/s | Concurrent errors | Downloads MB/s | Upload MB/s | WS RTT median (ms) | WS echoed / failed |\n")
	p("|---|---|---|---|---|---|---|---|---|---|---|---|\n")
	for _, r := range runs {
		probe := "—"
		if len(r.Probes) > 0 && r.Probes[0].OK > 0 {
			probe = num(r.Probes[0].MedianMs, 1)
		}
		lat := "—"
		if st := r.Latency.Stats; st != nil {
			lat = num(st.Median, 1) + " / " + num(st.P95, 1) + " / " + num(st.P99, 1)
		}
		ws := "—"
		if st := r.WebSocket.Stats; st != nil {
			ws = num(st.Median, 1)
		}
		p("| %s | %d | %s | %s | %s | %d | %.1f | %d | %s | %s | %s | %d / %d |\n",
			r.Target, r.Round, r.StartedAt.Format("2006-01-02 15:04"), probe, lat, r.Latency.Errors,
			r.Concurrency.ReqPerSec, r.Concurrency.Errors, transfers(r.Downloads), transfers(r.Uploads),
			ws, r.WebSocket.Echoed, r.WebSocket.Failures)
	}

	p("\n## Extra TCP probes\n\n")
	found := false
	for _, r := range runs {
		for _, pr := range r.Probes[min(1, len(r.Probes)):] {
			if !found {
				p("| Target | Round | Address | Median connect (ms) | OK |\n|---|---|---|---|---|\n")
				found = true
			}
			p("| %s | %d | %s | %.1f | %d / %d |\n", r.Target, r.Round, pr.Addr, pr.MedianMs, pr.OK, pr.Attempts)
		}
	}
	if !found {
		p("None.\n")
	}

	p("\n## Errors seen\n\n")
	found = false
	for _, r := range runs {
		var lines []string
		add := func(phase string, log []ErrorCount) {
			for _, e := range log {
				lines = append(lines, fmt.Sprintf("  - %s: %d × `%s`", phase, e.Count, strings.ReplaceAll(e.Error, "`", "'")))
			}
		}
		add("latency", r.Latency.ErrorLog)
		add("concurrency", r.Concurrency.ErrorLog)
		for i, t := range r.Downloads {
			if t.Error != "" {
				lines = append(lines, fmt.Sprintf("  - download %d: `%s`", i+1, strings.ReplaceAll(t.Error, "`", "'")))
			}
		}
		for i, t := range r.Uploads {
			if t.Error != "" {
				lines = append(lines, fmt.Sprintf("  - upload %d: `%s`", i+1, strings.ReplaceAll(t.Error, "`", "'")))
			}
		}
		add("websocket", r.WebSocket.ErrorLog)
		if len(lines) == 0 {
			continue
		}
		found = true
		p("- **%s, round %d**\n%s\n", r.Target, r.Round, strings.Join(lines, "\n"))
	}
	if !found {
		p("None.\n")
	}
}

func distinct(runs []*Result, f func(*Result) string) []string {
	seen := map[string]bool{}
	var out []string
	for _, r := range runs {
		v := f(r)
		if v == "" || seen[v] {
			continue
		}
		seen[v] = true
		out = append(out, v)
	}
	return out
}

func cell(values []string) string {
	if len(values) == 0 {
		return "—"
	}
	return strings.ReplaceAll(strings.Join(values, "; "), "|", "/")
}

func med(values []float64, decimals int) string {
	if len(values) == 0 {
		return "—"
	}
	return num(median(values), decimals)
}

// num shows sub-10 values (loopback milliseconds) with two decimals, so they
// don't all collapse to 0.0.
func num(v float64, decimals int) string {
	if v < 10 && decimals < 2 {
		decimals = 2
	}
	return fmt.Sprintf("%.*f", decimals, v)
}

func transfers(ts []Transfer) string {
	if len(ts) == 0 {
		return "—"
	}
	parts := make([]string, len(ts))
	for i, t := range ts {
		switch {
		case t.OK:
			parts[i] = fmt.Sprintf("%.2f", t.MBps)
		case t.PartialMBps > 0:
			parts[i] = fmt.Sprintf("~%.2f (timed out at %s)", t.PartialMBps, humanBytes(t.Received))
		default:
			parts[i] = "failed"
		}
	}
	return strings.Join(parts, ", ")
}

// rate is the median completed-transfer rate, or the partial rate when no
// transfer completed.
func rate(ok, partial []float64) string {
	if len(ok) > 0 || len(partial) == 0 {
		return med(ok, 2)
	}
	return "~" + med(partial, 2) + " (timed out)"
}

func humanBytes(n int64) string {
	switch {
	case n >= 1_000_000:
		return fmt.Sprintf("%g MB", float64(n)/1e6)
	case n >= 1_000:
		return fmt.Sprintf("%g kB", float64(n)/1e3)
	}
	return fmt.Sprintf("%d B", n)
}
